export function articleBySlug(slug: string): Article | undefined {
  return ARTICLES.find((article) => article.slug === slug);
}

export function articlesForSpecies(speciesId: string): Article[] {
  return ARTICLES.filter((article) => article.speciesId === speciesId);
}

/** Другие статьи той же темы (вида), без текущей. */
export function relatedArticles(slug: string, limit = 6): Article[] {
  const current = articleBySlug(slug);
  if (!current) return [];
  return articlesForSpecies(current.speciesId)
    .filter((article) => article.slug !== slug)
    .slice(0, limit);
}

export type ArticleCategoryId = "all" | "cat" | "dog" | "chicken";

export type ArticleCategory = {
  id: ArticleCategoryId;
  title: string;
  articles: Article[];
};

export const ARTICLES_PER_PAGE = 4;

const CATEGORY_IDS: ArticleCategoryId[] = ["all", "cat", "dog", "chicken"];

/** Категории-фильтры: все / кошки / собаки / курицы. */
export function articlesByCategory(): ArticleCategory[] {
  const categories: ArticleCategory[] = [
    { id: "all", title: "Все статьи", articles: [...ARTICLES] },
    { id: "cat", title: "Кошки", articles: articlesForSpecies("cat") },
    { id: "dog", title: "Собаки", articles: articlesForSpecies("dog") },
    { id: "chicken", title: "Курицы", articles: articlesForSpecies("chicken") },
  ];
  return categories.filter((category) => category.articles.length > 0);
}

export function isArticleCategoryId(value: string): value is ArticleCategoryId {
  return (CATEGORY_IDS as string[]).includes(value);
}

export function parseArticleCategory(raw: unknown): ArticleCategoryId {
  const value = Array.isArray(raw) ? raw[0] : raw;
  if (typeof value === "string" && isArticleCategoryId(value)) return value;
  return "all";
}

export function parseArticlePage(raw: unknown): number {
  const value = Array.isArray(raw) ? raw[0] : raw;
  const n = typeof value === "number" ? value : Number(value);
  if (!Number.isFinite(n) || n < 1) return 1;
  return Math.floor(n);
}

export function articlePageCount(total: number, perPage = ARTICLES_PER_PAGE): number {
  return Math.max(1, Math.ceil(total / perPage));
}

export function paginateArticles<T>(items: T[], page: number, perPage = ARTICLES_PER_PAGE): T[] {
  const safePage = Math.max(1, page);
  const start = (safePage - 1) * perPage;
  return items.slice(start, start + perPage);
}
