export function legalDocBySlug(slug: string): LegalDocument | undefined {
  return LEGAL_DOCUMENTS.find((doc) => doc.slug === slug);
}

export function fillLegalPlaceholders(
  text: string,
  operatorName: string,
  operatorEmail: string,
): string {
  return text
    .replaceAll(LEGAL_OPERATOR_PLACEHOLDER, operatorName)
    .replaceAll(LEGAL_EMAIL_PLACEHOLDER, operatorEmail);
}
